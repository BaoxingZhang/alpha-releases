const WECHAT_EMOJIS = Object.fromEntries(
  EMOJI_ALIASES.flatMap(([file, aliases]) => aliases.map((alias) => [alias, `./wxemoji/${file}`]))
);
const keys = Object.keys(WECHAT_EMOJIS).sort((a, b) => b.length - a.length);
const pattern = keys.map((key) => key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|");
function messageTextSegments(text) {
  const output = [];
  let offset = 0;
  for (const match of text.matchAll(new RegExp(pattern, "gu"))) {
    if (match.index > offset) output.push({ kind: "text", text: text.slice(offset, match.index), offset });
    output.push({ kind: "emoji", text: match[0], src: WECHAT_EMOJIS[match[0]], offset: match.index });
    offset = match.index + match[0].length;
  }
  if (offset < text.length) output.push({ kind: "text", text: text.slice(offset), offset });
  return output;
}
